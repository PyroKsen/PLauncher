const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('api', {
  getLauncherUpdateState: () => ipcRenderer.invoke('get-launcher-update-state'),
  checkLauncherUpdate: () => ipcRenderer.invoke('check-launcher-update'),
  downloadLauncherUpdate: () => ipcRenderer.invoke('download-launcher-update'),
  installLauncherUpdate: () => ipcRenderer.invoke('install-launcher-update'),
  onLauncherUpdateState: (cb) => ipcRenderer.on('launcher-update-state', (e, d) => cb(d)),
  getLogPath: () => ipcRenderer.invoke('get-log-path'),
  openLogs: () => ipcRenderer.invoke('open-logs'),
  writeRendererLog: (level, args) => ipcRenderer.invoke('renderer-log', level, args),
  getLauncherWriteAccess: () => ipcRenderer.invoke('get-launcher-write-access'),
  getGamesDir: () => ipcRenderer.invoke('get-games-dir'),
  chooseGamesDir: () => ipcRenderer.invoke('choose-games-dir'),
  minimizeWindow: () => ipcRenderer.invoke('minimize-window'),
  closeWindow: () => ipcRenderer.invoke('close-window'),
  openGameFolder: (gameName) => ipcRenderer.invoke('open-game-folder', gameName),
  startDownload: (url, gameName, remoteVersion, remoteDirName) => ipcRenderer.invoke('start-download', url, gameName, remoteVersion, remoteDirName),
  controlDownload: (action, url) => ipcRenderer.invoke('download-control', action, url),
  onExtractStart: (cb) => ipcRenderer.on('extract-start', (e, d) => cb(d)),
  onExtractDone: (cb) => ipcRenderer.on('extract-done', (e, d) => cb(d)),
  onExtractError: (cb) => ipcRenderer.on('extract-error', (e, d) => cb(d)),
  onDownloadProgress: (cb) => ipcRenderer.on('download-progress', (e, d) => cb(d)),
  onDownloadDone: (cb) => ipcRenderer.on('download-done', (e, d) => cb(d)),
  onExtractProgress: (cb) => ipcRenderer.on('extract-progress', (e, d) => cb(d)),

  launchGame: (gameName) => ipcRenderer.invoke('launch-game', gameName),
  onGameStarted: (cb) => ipcRenderer.on('game-started', (e, d) => cb(d)),
  onGameExited: (cb) => ipcRenderer.on('game-exited', (e, d) => cb(d)),
  onGameError: (cb) => ipcRenderer.on('game-error', (e, d) => cb(d)),
  checkVersion: (gameName) => ipcRenderer.invoke('check-version', gameName),
  onGameVersionsChecked: (cb) => ipcRenderer.on('game-versions-checked', (_event, states) => cb(states)),
  updateLocalVersion: (gameName, newVersion) => ipcRenderer.invoke('update-local-version', gameName, newVersion),
});
